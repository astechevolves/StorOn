"""Regenerate src/web_assets.h from the PNGs in this folder.

Run from the firmware folder:  python assets/make_web_assets.py
logo.png    - header banner (scaled from images/Storon Logo.png)
favicon.png - 64x64 browser tab icon (the red hexagon)
icon180.png - 180x180 home-screen icon
"""
from pathlib import Path

HERE = Path(__file__).parent
FILES = [("LOGO_PNG", "logo.png"), ("FAVICON_PNG", "favicon.png"), ("ICON180_PNG", "icon180.png")]

out = ["#pragma once", "// Generated by assets/make_web_assets.py - do not edit by hand.", "#include <Arduino.h>", ""]
for name, file in FILES:
    data = (HERE / file).read_bytes()
    out.append(f"static const uint8_t {name}[] PROGMEM = {{")
    for i in range(0, len(data), 20):
        out.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    out.append("};")
    out.append(f"static const size_t {name}_LEN = {len(data)};")
    out.append("")
(HERE.parent / "src" / "web_assets.h").write_text("\n".join(out), encoding="ascii")
print("wrote src/web_assets.h")
